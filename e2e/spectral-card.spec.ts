  await expect(page.locator('.hr-reference-marker')).toHaveCount(1)
  await expectDistinctMarkerLabels(page, 'hr')
  const selectedBounds = await page.locator('#selected-object-card').boundingBox()
  const cardBounds = await card.boundingBox()
  expect(cardBounds!.x).toBeGreaterThan(selectedBounds!.x + selectedBounds!.width)
  await page.screenshot({ path: testInfo.outputPath('hr-sirius-a.png') })

  await page.locator('#spectral-bolometric').click()
  await expect(page.locator('#spectral-bolometric')).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('#spectral-reference-magnitude')).toHaveText('4.74')
  await page.keyboard.press('Escape')
  await expect(card).toBeHidden()
  await expect(toggle).toBeFocused()

