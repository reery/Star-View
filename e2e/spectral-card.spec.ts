  await expect(page.locator('#spectral-selected-name')).toHaveText('Sirius B')
  await expect(page.locator('#spectral-selected-type')).toContainText('DA')
  const whiteDwarf = await page.locator('.hr-selected-marker circle').first().evaluate((circle) => ({ x: Number(circle.getAttribute('cx')), y: Number(circle.getAttribute('cy')) }))
