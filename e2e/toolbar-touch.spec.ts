import { expect, test } from '@playwright/test'
import { openViewer } from './support'

test('toolbar hover, keyboard access and single-click actions stay unchanged', async ({ page, isMobile }) => {
  test.skip(isMobile, 'Desktop pointer behavior')
  await openViewer(page)
  for (const name of ['camera-view', 'grid', 'selection', 'origin', 'observer-view']) {
    const group = page.locator(`.${name}-controls`)
    // Selection starts with no available history.
    if (name === 'selection') continue
    await group.hover()
    await expect(group.locator('[data-toolbar-options]')).toBeVisible()
    await expect(group).not.toHaveAttribute('data-touch-open')
    await page.mouse.move(5, 5)
    await expect(group.locator('[data-toolbar-options]')).toBeHidden()
  }
  const grid = page.locator('#toggle-grid')
  const before = await grid.getAttribute('aria-pressed')
  await grid.click()
  await expect(grid).toHaveAttribute('aria-pressed', String(before !== 'true'))
  await grid.focus()
  await page.keyboard.press('Tab')
  await expect(page.locator('#toggle-equatorial-grid')).toBeFocused()
})

test('touch reveals toolbar options without firing the main action @mobile', async ({ page, isMobile }, testInfo) => {
  test.skip(!isMobile, 'Real touch input')
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await openViewer(page)
  const grid = page.locator('#toggle-grid')
  const equatorial = page.locator('#toggle-equatorial-grid')
  const before = await grid.getAttribute('aria-pressed')
  await grid.tap()
  await expect(equatorial).toBeVisible()
  await expect(grid).toHaveAttribute('aria-pressed', before!)
  await grid.tap()
  await expect(grid).toHaveAttribute('aria-pressed', String(before !== 'true'))
  await equatorial.tap()
  await expect(page.locator('#scene')).toHaveAttribute('data-sky-grid', 'equatorial')
  await page.screenshot({ path: testInfo.outputPath('touch-grid-expanded.png') })
  await page.locator('#views-toggle').tap()
  await expect(equatorial).toBeHidden()
  await expect(page.locator('#views-panel')).toBeVisible()
  await page.locator('#views-toggle').tap()

  // Opening origin options must not change the reference object.
  const origin = page.locator('#set-origin')
  await origin.tap()
  await expect(page.locator('#set-sun-origin')).toBeVisible()
  await expect(origin).toBeEnabled()
  await expect(page.locator('#go-to-origin-name')).toHaveText('Sun')
  await origin.tap()
  await expect(page.locator('#go-to-origin-name')).toHaveText('Sirius A')
  await page.locator('#set-sun-origin').tap()
  await expect(page.locator('#go-to-origin-name')).toHaveText('Sun')

  // Switching groups closes the previous expansion, without entering Observer.
  await page.locator('#observer-view').tap()
  await expect(page.locator('#set-sun-origin')).toBeHidden()
  await expect(page.locator('#observer-view-origin')).toBeVisible()
  await expect(page.locator('#observer-view')).toHaveAttribute('aria-pressed', 'false')
  await page.locator('#observer-view-origin').tap()
  await expect(page.locator('#scene')).toHaveAttribute('data-observer-view', 'true')
  await page.locator('#observer-view').tap()
  await expect(page.locator('#observer-view')).toHaveAttribute('aria-pressed', 'false')

  await page.locator('#reset-view').tap()
  await expect(page.locator('#observer-view-origin')).toBeHidden()
  await expect(page.locator('#top-view')).toBeVisible()
  await page.locator('#top-view').tap()
  await page.keyboard.press('Escape')
  await expect(page.locator('#top-view')).toBeHidden()
  expect(errors).toEqual([])
})

test('touch history works with a disabled main button and keeps keyboard navigation @mobile', async ({ page, isMobile }) => {
  test.skip(!isMobile, 'Real touch input')
  await openViewer(page)
  const group = page.locator('#selection-controls')
  const back = page.locator('#selection-back')
  const forward = page.locator('#selection-forward')
  await group.tap()
  await expect(forward).toBeHidden()
  await page.locator('#objects-toggle').tap()
  await page.getByRole('button', { name: 'Select Sun', exact: true }).tap()
  await back.tap()
  await expect(page.locator('#star-name')).toHaveText('Sun')
  await expect(forward).toBeVisible()
  await back.tap()
  await expect(page.locator('#star-name')).toHaveText('Sirius')
  await expect(back).toBeDisabled()
  await page.locator('#objects-toggle').tap()
  await expect(forward).toBeHidden()
  await group.tap()
  await expect(forward).toBeVisible()
  await forward.tap()
  await expect(page.locator('#star-name')).toHaveText('Sun')
  await page.locator('#toggle-grid').tap()
  await expect(forward).toBeHidden()
  await page.locator('#toggle-grid').focus()
  await page.keyboard.press('Tab')
  await expect(page.locator('#toggle-equatorial-grid')).toBeFocused()
})
