import { expect, test, type Page } from '@playwright/test'
import { selectCatalog } from './support'

async function selectHost(page: Page, name: string) {
  if (await page.locator('#planet-card').isVisible()) await page.keyboard.press('Escape')
  const objects = page.getByRole('button', { name: 'Objects', exact: true })
  if (await objects.getAttribute('aria-expanded') === 'false') await objects.click()
  await page.getByLabel('Search objects').fill(name)
  await page.getByRole('button', { name: `Select ${name}`, exact: true }).click()
  if (await objects.getAttribute('aria-expanded') === 'true') await objects.click()
  if (await page.locator('#object-system-toggle').getAttribute('aria-expanded') === 'false') await page.locator('#object-system-toggle').click()
}

test('habitable zone starts off, aligns with planets and handles unavailable hosts @mobile', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/')
  await expect(page.locator('#scene')).toHaveAttribute('data-ready', 'true')
  await selectHost(page, 'Sun')
  const toggle = page.getByRole('button', { name: 'Habitable zone', exact: true })
  const band = page.locator('.planet-habitable-zone path')
  await expect(toggle).toBeEnabled()
  await expect(toggle).toHaveAttribute('aria-pressed', 'false')
  await expect(band).toHaveCount(0)
  const earthX = await page.locator('[data-planet-id="earth"] .planet-marker').getAttribute('cx')
  await toggle.focus()
  await page.keyboard.press('Enter')
  await expect(toggle).toHaveAttribute('aria-pressed', 'true')
  await expect(band).toBeVisible()
  await expect(page.locator('.planet-orbit-diagram').first()).toHaveAttribute('aria-label', /Conservative habitable zone/)
  expect(await page.locator('[data-planet-id="earth"] .planet-marker').getAttribute('cx')).toBe(earthX)
  const edges = await band.evaluate((element) => ({ inner: Number(element.getAttribute('data-inner-au')), outer: Number(element.getAttribute('data-outer-au')) }))
  expect(edges.inner).toBeLessThan(1)
  expect(edges.outer).toBeGreaterThan(1)
  expect(edges.outer).toBeLessThan(1.7)
  await page.locator('.planet-row[data-planet-id="earth"] button').click()
  await expect(page.locator('#planet-card')).toBeVisible()
  await expect(page.locator('.planet-body[data-planet-id="earth"]')).toHaveClass(/is-highlighted/)
  await toggle.focus()
  await page.keyboard.press('Enter')
  await expect(band).toHaveCount(0)
  await expect(page.locator('.planet-body[data-planet-id="earth"]')).toHaveClass(/is-highlighted/)
  await expect(page.locator('.planet-row[data-planet-id="earth"] button')).toHaveAttribute('aria-expanded', 'true')
  await page.keyboard.press('Escape')
  await selectHost(page, "Barnard's Star")
  await expect(toggle).toHaveAttribute('aria-pressed', 'false')
  await toggle.click()
  await expect(band).toBeVisible()
  await page.locator('#selected-object-card').screenshot({ path: testInfo.outputPath('barnard-habitable-zone.png') })
  expect(await page.locator('#object-system').evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true)
  await selectCatalog(page, 'nearest-1000')
  await selectHost(page, 'TRAPPIST-1')
  await expect(toggle).toBeDisabled()
  await expect(toggle).toHaveAttribute('title', /2600–7200 K/)
  await expect(band).toHaveCount(0)
  expect(errors).toEqual([])
})
