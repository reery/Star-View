import { expect, test } from '@playwright/test'
import { openSpecs, openViewer } from './support'

test('shows conditional WISE mass and infrared magnitude without filling visual photometry or radial velocity', async ({ page }, testInfo) => {
  await openViewer(page)
  await page.getByRole('button', { name: 'Objects', exact: true }).click()
  await page.getByLabel('Search objects').fill('WISE 0855')
  await page.getByRole('button', { name: 'Select WISE 0855-0714', exact: true }).click()
  await openSpecs(page)
  await expect(page.locator('#mass-label')).toHaveText('Mass (model)')
  await expect(page.locator('#mass')).toHaveText('3–10 M♃')
  await expect(page.locator('#mass')).toHaveAttribute('aria-label', /assuming an age of 1 to 10 billion years/)
  await expect(page.locator('#mass-toggle')).toBeDisabled()
  await expect(page.locator('#infrared-magnitude-label')).toHaveText('Apparent mag. (W2)')
  await expect(page.locator('#infrared-magnitude')).toHaveText('13.89 ± 0.05')
  await expect(page.locator('#infrared-magnitude')).toHaveAttribute('title', /4.6 μm, Vega.*2010-05-04.*subtracting the two stationary background sources/)
  await expect(page.locator('#absolute-mag')).toHaveText('—')
  await expect(page.locator('#apparent-mag')).toHaveText('—')
  await expect(page.locator('#magnitude-toggle')).toBeDisabled()
  await page.screenshot({ path: testInfo.outputPath('wise-0855-observations.png'), fullPage: true })
  await page.getByText('Coordinates & source', { exact: true }).click()
  await expect(page.locator('#radial-velocity')).toHaveText('—')
  await expect(page.locator('#radial-velocity')).toHaveAttribute('title', /wavelength-calibration differences/)
  await expect(page.locator('#motion-data')).toHaveText('Transverse only; radial velocity unavailable')
  await page.getByLabel('Search objects').fill('Sirius')
  await page.getByRole('button', { name: 'Select Sirius A', exact: true }).click()
  await expect(page.locator('#infrared-magnitude-row')).toBeHidden()
  await expect(page.locator('#mass-label')).toHaveText('Mass')
  await expect(page.locator('#mass')).not.toHaveAttribute('aria-label', /Model mass/)
})
