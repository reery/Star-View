import { expect, test, type Page } from '@playwright/test'
import { selectCatalog } from './support'

async function select(page: Page, name: string) {
  if (await page.locator('#luminosity-card').isVisible()) await page.locator('#luminosity-close').click()
  await page.getByRole('button', { name: 'Objects', exact: true }).click()
  await page.getByLabel('Search objects').fill(name)
  await page.getByRole('button', { name: `Select ${name}`, exact: true }).click()
  await page.getByRole('button', { name: 'Objects', exact: true }).click()
  if (await page.locator('#object-card-details').getAttribute('open') === null) await page.locator('#object-specs-toggle').click()
}

test('shows the surface-power calculation and equal-flux distances, and follows card lifecycle', { tag: '@mobile' }, async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/')
  await expect(page.locator('#scene')).toHaveAttribute('data-ready', 'true')
  await expect(page.locator('#scene-status')).toBeHidden()
  await page.locator('#object-specs-toggle').click()
  const card = page.locator('#luminosity-card')
  const toggle = page.locator('#luminosity-toggle')
  await toggle.hover()
  const hoverBounds = await page.locator('#luminosity-row').evaluate((row) => ({
    positioned: getComputedStyle(row).position, isolated: getComputedStyle(row).isolation,
    highlightHeight: getComputedStyle(row.querySelector('button')!, '::before').height,
    rowHeight: row.getBoundingClientRect().height,
  }))
  expect(hoverBounds.positioned).toBe('relative')
  expect(hoverBounds.isolated).toBe('isolate')
  expect(Number.parseFloat(hoverBounds.highlightHeight)).toBeCloseTo(hoverBounds.rowHeight + 2, 3)
  await page.locator('#luminosity-row dt').click()
  await expect(card).toBeVisible()
  await expect(toggle).toHaveAttribute('aria-expanded', 'true')
  await expect(page.locator('#luminosity-heading')).toHaveText('Bolometric luminosity')
  await expect(page.locator('#luminosity-area')).toHaveText('2.94')
  await expect(page.locator('#luminosity-surface-flux')).toHaveText('8.46')
  await expect(page.locator('#luminosity-calculated-solar')).toHaveText('24.9 L☉')
  await expect(page.locator('#luminosity-flux-origin-name')).toHaveText('Sun')
  await expect(page.locator('#luminosity-flux-origin-distance')).toHaveText('1 AU')
  await expect(page.locator('#luminosity-flux-selected-distance')).toHaveText('4.97 AU')
  await expect(page.locator('#luminosity-flux-origin-value')).toHaveText('1,360 W/m²')
  await expect(page.locator('#luminosity-flux-selected-orbit')).toHaveText('(about Jupiter’s orbit)')
  await expect(page.locator('#luminosity-flux-origin-orbit')).toBeHidden()
  await expect(page.locator('#luminosity-flux-sun')).toBeHidden()
  await expect(page.locator('#luminosity-flux-selected-bar .luminosity-orbit-tick > span')).toHaveText(['Mars'])
  await expect(page.locator('#luminosity-flux-origin-bar .luminosity-orbit-tick')).toHaveCount(0)
  await expect(page.locator('#luminosity-class-heading')).toHaveText('A-type main-sequence star')
  await expect(page.locator('#luminosity-class-context')).toBeHidden()
  await expect(page.locator('#luminosity-class-median-value')).toContainText('Median')
  await expect(page.locator('#luminosity-class-bar')).toHaveAttribute('aria-label', /Middle 80% of catalog luminosities/)
  const bounds = await card.boundingBox()
  expect(bounds!.x).toBeGreaterThanOrEqual(0)
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(page.viewportSize()!.width)
  const overflow = await card.evaluate((element) => {
    const bounds = element.getBoundingClientRect()
    return { pixels: element.scrollWidth - element.clientWidth, children: [...element.querySelectorAll('*')].filter((child) => {
      const box = child.getBoundingClientRect()
      return box.width > 0 && (box.left < bounds.left || box.right > bounds.right)
    }).map((child) => `${child.id || child.className}: ${child.getBoundingClientRect().left}…${child.getBoundingClientRect().right}`) }
  })
  expect(overflow).toEqual({ pixels: 0, children: [] })
  await page.screenshot({ path: testInfo.outputPath('luminosity-sirius.png') })
  const scroll = card.locator('.card-scroll-content')
  await scroll.evaluate((element) => { element.scrollTop = element.scrollHeight })
  await page.locator('#luminosity-close').click()
  await expect(toggle).toBeFocused()
  await toggle.click()
  await expect.poll(() => scroll.evaluate((element) => element.scrollTop)).toBe(0)
  await page.keyboard.press('Escape')
  await expect(card).toBeHidden()
  await expect(toggle).toBeFocused()
  await page.locator('#mass-toggle').click()
  await toggle.focus()
  await toggle.press('Enter')
  await expect(page.locator('#mass-card')).toBeHidden()
  await expect(card).toBeVisible()
  await page.locator('#radius-toggle').focus()
  await page.locator('#radius-toggle').press('Enter')
  await expect(card).toBeHidden()
  await toggle.focus()
  await toggle.press('Enter')
  await expect(page.locator('#radius-card')).toBeHidden()

  await select(page, 'Proxima Centauri')
  await page.locator('#star-components [data-component-id="proxima-centauri"]').click()
  if (await card.isHidden()) await toggle.click()
  await expect(page.locator('#luminosity-flux-selected-name')).toHaveText('Proxima Centauri')
  await expect(page.locator('#luminosity-flux-selected-distance')).toHaveText('0.038 AU')
  await expect(page.locator('#luminosity-flux-selected-orbit')).toBeHidden()
  await expect(page.locator('#luminosity-flux-selected-bar .luminosity-orbit-tick > span')).toHaveText(['Mercury', 'Venus'])
  await page.locator('#set-origin').click()
  await expect(page.locator('#luminosity-flux-origin-name')).toHaveText('Proxima Centauri')
  await expect(page.locator('#luminosity-flux-selected-distance')).toHaveText('1 AU')
  await expect(page.locator('#luminosity-flux-selected-orbit')).toHaveText('(about Earth’s orbit)')
  await expect(page.locator('#luminosity-flux-sun')).toBeVisible()
  await expect(page.locator('#luminosity-flux-sun-distance')).toHaveText('26.3 AU')
  await expect(page.locator('#luminosity-flux-origin-value')).toHaveText('1.96 W/m²')
  await expect(page.locator('#luminosity-flux-sun-orbit')).toBeHidden()
  await expect(page.locator('#luminosity-flux-sun-bar .luminosity-orbit-tick > span')).toHaveText(['Jupiter'])
  await expect(page.locator('#luminosity-flux-selected-bar .luminosity-orbit-tick')).toHaveCount(0)
  await page.screenshot({ path: testInfo.outputPath('luminosity-proxima-origin.png') })
  expect(errors).toEqual([])
})

test('handles missing luminosity and expands the scale for an ultracool object', { tag: '@mobile' }, async ({ page }, testInfo) => {
  await page.goto('/')
  await expect(page.locator('#scene')).toHaveAttribute('data-ready', 'true')
  await selectCatalog(page, 'nearest-100')
  await expect(page.locator('#scene-status')).toBeHidden()
  await page.getByRole('button', { name: 'Filter', exact: true }).click()
  await select(page, 'WISE 0855-0714')
  await page.locator('#luminosity-toggle').click()
  await expect(page.locator('#luminosity-scale-low')).toHaveText('10⁻⁹ L☉')
  await expect(page.locator('#luminosity-class-bar')).toBeHidden()
  await expect(page.locator('#luminosity-class-context')).toContainText('Too few measured peers')
  const position = await page.locator('#luminosity-scale').evaluate((element) => Number.parseFloat((element as HTMLElement).style.getPropertyValue('--mass-ratio-position')))
  expect(position).toBeGreaterThan(0)
  expect(position).toBeLessThan(10)
  await page.screenshot({ path: testInfo.outputPath('luminosity-wise-0855.png') })
  await select(page, 'Luhman 16 A')
  if (await page.locator('#luminosity-card').isHidden()) await page.locator('#luminosity-toggle').click()
  await expect(page.locator('#luminosity-class-heading')).toHaveText('L-type brown dwarf')
  await expect(page.locator('#luminosity-class-median-value')).toContainText('Median')
  await expect(page.locator('#luminosity-class-bar')).toHaveAttribute('aria-label', /Middle 80% of catalog luminosities/)
  await page.screenshot({ path: testInfo.outputPath('luminosity-luhman-16.png') })
  await select(page, 'EZ Aquarii A')
  await expect(page.locator('#luminosity-toggle')).toBeDisabled()
  await expect(page.locator('#luminosity')).toHaveText('—')
  await expect(page.locator('#luminosity-card')).toBeHidden()
})
