import { expect, test, type Page } from '@playwright/test'
import { selectCatalog } from './support'

async function select(page: Page, name: string) {
  if (await page.locator('#luminosity-card').isVisible()) await page.locator('#luminosity-close').click()
  await page.getByRole('button', { name: 'Objects', exact: true }).click()
  await page.getByLabel('Search objects').fill(name)
  await page.getByRole('button', { name: `Select ${name}`, exact: true }).click()
  await page.getByRole('button', { name: 'Objects', exact: true }).click()
  if (await page.locator('#object-card-details').getAttribute('open') === null) await page.locator('#object-specs-toggle').click()
}

test('shows adopted luminosity with derived surface flux and equal-flux distances, and follows card lifecycle', { tag: '@mobile' }, async ({ page, isMobile }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/')
  await expect(page.locator('#scene')).toHaveAttribute('data-ready', 'true')
  await expect(page.locator('#scene-status')).toBeHidden()
  await page.locator('#object-specs-toggle').click()
  const card = page.locator('#luminosity-card')
  const toggle = page.locator('#luminosity-toggle')
  await toggle.hover()
  const hoverBounds = await page.locator('#luminosity-row').evaluate((row) => ({
    positioned: getComputedStyle(row).position, isolated: getComputedStyle(row).isolation,
    highlightHeight: getComputedStyle(row.querySelector('button')!, '::before').height,
    rowHeight: row.getBoundingClientRect().height,
  }))
  expect(hoverBounds.positioned).toBe('relative')
  expect(hoverBounds.isolated).toBe('isolate')
  expect(Number.parseFloat(hoverBounds.highlightHeight)).toBeCloseTo(hoverBounds.rowHeight + 2, 3)
  await page.locator('#luminosity-row dt').click()
  await expect(card).toBeVisible()
  await expect(toggle).toHaveAttribute('aria-expanded', 'true')
  await expect(page.locator('#luminosity-heading')).toHaveText('Bolometric luminosity')
  await expect(page.locator('#luminosity-area')).toHaveText('2.94')
  await expect(page.locator('#luminosity-surface-flux')).toHaveText('8.42')
  await expect(page.locator('#luminosity-solar')).toHaveText('24.7 L☉')
  await expect(card.locator('.luminosity-equation > .planet-fact-tile:visible')).toHaveCount(3)
  const tilePadding = await card.locator('.luminosity-equation > .planet-fact-tile:visible').evaluateAll((tiles) => tiles.map((tile) => getComputedStyle(tile).padding))
  expect(tilePadding).toEqual(['8px 10px', '8px 10px', '8px 10px'])
  const tileTops = await card.locator('.luminosity-equation > .planet-fact-tile:visible').evaluateAll((tiles) => tiles.map((tile) => tile.getBoundingClientRect().top))
  expect(Math.max(...tileTops) - Math.min(...tileTops)).toBeLessThan(1)
  await expect(card.locator('.luminosity-factor-title')).toHaveText(['Surface area', 'Surface flux', 'Bolometric luminosity'])
  await expect(page.locator('#luminosity-calculation-note')).toBeHidden()
  await expect(page.locator('#luminosity-area-icon svg')).toBeVisible()
  await expect(page.locator('#luminosity-surface-flux-icon svg')).toBeVisible()
  await expect(page.locator('#luminosity-result-star')).toBeVisible()
  const resultAppearance = () => card.evaluate((element) => ({
    color: getComputedStyle(element).getPropertyValue('--luminosity-real-color').trim(),
    star: getComputedStyle(element.querySelector('#luminosity-result-star')!).backgroundImage,
    starGlow: getComputedStyle(element.querySelector('#luminosity-result-star')!).boxShadow,
    tileGlow: getComputedStyle(element.querySelector('.luminosity-result')!).boxShadow,
  }))
  const siriusAppearance = await resultAppearance()
  expect(siriusAppearance.star.replace(/\s/g, '')).toContain(siriusAppearance.color.replace(/\s/g, ''))
  expect(siriusAppearance.starGlow).not.toBe('none')
  expect(siriusAppearance.tileGlow).not.toBe('none')
  if (!isMobile) {
    await page.getByRole('button', { name: 'Preferences', exact: true }).click()
    await page.locator('#star-colors-real').check()
    expect(await resultAppearance()).toEqual(siriusAppearance)
    await page.locator('#star-colors-exaggerated').check()
    await page.getByRole('button', { name: 'Preferences', exact: true }).click()
  }
  await expect(page.locator('#luminosity-flux-origin-name')).toHaveText('Sun')
  await expect(page.locator('#luminosity-flux-origin-distance')).toHaveText('1 AU')
  await expect(page.locator('#luminosity-flux-selected-distance')).toHaveText('4.97 AU')
  await expect(page.locator('#luminosity-flux-origin-value')).toHaveText('1,360 W/m² at 1 AU')
  await expect(page.locator('#luminosity-flux-selected-value')).toHaveText('33,700 W/m² at 1 AU')
  await expect(card).not.toContainText('about Jupiter')
  await expect(page.locator('#luminosity-flux-bar-selected-label')).toHaveText('Sirius A (5.0 AU)')
  await expect(page.locator('#luminosity-flux-sun')).toBeHidden()
  await expect(page.locator('#luminosity-flux-bar .luminosity-orbit-tick > .luminosity-plot-label')).toHaveText(['Earth', 'Mars', 'Jupiter'])
  await expect(page.locator('.luminosity-distance-bar')).toHaveCount(1)
  await expect(page.locator('#luminosity-class-heading')).toHaveText('A-type main-sequence star')
  await expect(page.locator('#luminosity-class-context')).toBeHidden()
  await expect(page.locator('#luminosity-class-median-value')).toContainText('Median')
  await expect(page.locator('#luminosity-class-bar')).toHaveAttribute('aria-label', /Middle 80% of catalog luminosities/)
  const bounds = await card.boundingBox()
  expect(bounds!.x).toBeGreaterThanOrEqual(0)
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(page.viewportSize()!.width)
  const overflow = await card.evaluate((element) => {
    const bounds = element.getBoundingClientRect()
    return { pixels: element.scrollWidth - element.clientWidth, children: [...element.querySelectorAll('*')].filter((child) => {
      const box = child.getBoundingClientRect()
      return box.width > 0 && (box.left < bounds.left || box.right > bounds.right)
    }).map((child) => `${child.id || child.className}: ${child.getBoundingClientRect().left}…${child.getBoundingClientRect().right}`) }
  })
  // Match the temperature card's tolerance for rounded border geometry.
  expect(overflow.pixels).toBeLessThanOrEqual(1)
  expect(overflow.children).toEqual([])
  await page.screenshot({ path: testInfo.outputPath('luminosity-sirius.png') })
  const scroll = card.locator('.card-scroll-content')
  await scroll.evaluate((element) => { element.scrollTop = element.scrollHeight })
  await page.locator('#luminosity-close').click()
  await expect(toggle).toBeFocused()
  await toggle.click()
  await expect.poll(() => scroll.evaluate((element) => element.scrollTop)).toBe(0)
  await page.keyboard.press('Escape')
  await expect(card).toBeHidden()
  await expect(toggle).toBeFocused()
  await page.locator('#mass-toggle').click()
  await expect(page.locator('#mass-card')).toBeVisible()
  await toggle.focus()
  await toggle.press('Enter')
  await expect(page.locator('#mass-card')).toBeHidden()
  await expect(card).toBeVisible()
  await page.locator('#radius-toggle').focus()
  await page.locator('#radius-toggle').press('Enter')
  await expect(card).toBeHidden()
  await toggle.focus()
  await toggle.press('Enter')
  await expect(page.locator('#radius-card')).toBeHidden()

  await select(page, 'Proxima Centauri')
  await page.locator('#star-components [data-component-id="proxima-centauri"]').click()
  if (await card.isHidden()) await toggle.click()
  expect((await resultAppearance()).color).not.toBe(siriusAppearance.color)
  await expect(page.locator('#luminosity-flux-selected-name')).toHaveText('Proxima Centauri')
  await expect(page.locator('#luminosity-flux-selected-distance')).toHaveText('0.038 AU')
  await expect(page.locator('#luminosity-flux-selected-value')).toHaveText('1.96 W/m² at 1 AU')
  await expect(page.locator('#luminosity-distance-axis-high')).toHaveText('1 AU')
  await expect(page.locator('#luminosity-flux-bar-reference-label')).toHaveText('Sun (1.0 AU)')
  await expect(page.locator('#luminosity-flux-bar-selected-label')).toHaveText('Proxima Centauri (0.038 AU)')
  await expect(page.locator('#luminosity-flux-bar .luminosity-orbit-tick > .luminosity-plot-label')).toHaveText(['Mercury', 'Venus'])
  await page.locator('#set-origin').click()
  await expect(page.locator('#luminosity-flux-origin-name')).toHaveText('Proxima Centauri')
  await expect(page.locator('#luminosity-flux-selected-distance')).toHaveText('0.038 AU')
  await expect(page.locator('#luminosity-flux-sun')).toBeVisible()
  await expect(page.locator('#luminosity-flux-sun-distance')).toHaveText('1 AU')
  await expect(page.locator('#luminosity-flux-origin-value')).toHaveText('1.96 W/m² at 1 AU')
  await expect(page.locator('#luminosity-flux-sun-value')).toHaveText('1,360 W/m² at 1 AU')
  await expect(page.locator('#luminosity-distance-axis-high')).toHaveText('1 AU')
  await expect(page.locator('#luminosity-flux-bar .luminosity-orbit-tick > .luminosity-plot-label')).toHaveText(['Mercury', 'Venus'])
  await expect(page.locator('#luminosity-flux-bar .luminosity-object-marker')).toHaveCount(2)
  await page.screenshot({ path: testInfo.outputPath('luminosity-proxima-origin.png') })
  expect(errors).toEqual([])
})

test('matches the 61 Cyg B specs instead of recomputing luminosity from temperature', { tag: '@mobile' }, async ({ page }, testInfo) => {
  await page.goto('/')
  await expect(page.locator('#scene')).toHaveAttribute('data-ready', 'true')
  await selectCatalog(page, 'nearest-100')
  await expect(page.locator('#scene-status')).toBeHidden()
  await page.getByRole('button', { name: 'Filter', exact: true }).click()
  await select(page, '61 Cyg B')
  await page.locator('#luminosity-toggle').click()
  await expect(page.locator('#luminosity-area')).toHaveText('0.458')
  await expect(page.locator('#luminosity-surface-flux')).toHaveText('0.206')
  await expect(page.locator('#luminosity-solar')).toHaveText('0.0945 L☉')
  await expect(page.locator('#luminosity')).toContainText('0.1')
  await expect(page.locator('#luminosity-scale-value')).toHaveText('0.0945 L☉')
  await expect(page.locator('#luminosity-flux-selected-distance')).toHaveText('0.307 AU')
  await expect(page.locator('#luminosity-calculation-note')).toBeHidden()
  await page.screenshot({ path: testInfo.outputPath('luminosity-61-cyg-b.png') })
})

test('handles missing luminosity and expands the scale for an ultracool object', { tag: '@mobile' }, async ({ page }, testInfo) => {
  await page.goto('/')
  await expect(page.locator('#scene')).toHaveAttribute('data-ready', 'true')
  await selectCatalog(page, 'nearest-100')
  await expect(page.locator('#scene-status')).toBeHidden()
  await page.getByRole('button', { name: 'Filter', exact: true }).click()
  await select(page, 'WISE 0855-0714')
  await page.locator('#luminosity-toggle').click()
  await expect(page.locator('#luminosity-scale-low')).toHaveText('10⁻⁹ L☉')
  await expect(page.locator('#luminosity-class-bar')).toBeHidden()
  await expect(page.locator('#luminosity-class-context')).toContainText('Too few measured peers')
  const position = await page.locator('#luminosity-scale').evaluate((element) => Number.parseFloat((element as HTMLElement).style.getPropertyValue('--mass-ratio-position')))
  expect(position).toBeGreaterThan(0)
  expect(position).toBeLessThan(10)
  await page.screenshot({ path: testInfo.outputPath('luminosity-wise-0855.png') })
  await select(page, 'Luhman 16 A')
  if (await page.locator('#luminosity-card').isHidden()) await page.locator('#luminosity-toggle').click()
  await expect(page.locator('#luminosity-class-heading')).toHaveText('L-type brown dwarf')
  await expect(page.locator('#luminosity-class-median-value')).toContainText('Median')
  await expect(page.locator('#luminosity-class-bar')).toHaveAttribute('aria-label', /Middle 80% of catalog luminosities/)
  await page.screenshot({ path: testInfo.outputPath('luminosity-luhman-16.png') })
  await select(page, 'EZ Aquarii A')
  await page.locator('#luminosity-toggle').click()
  await expect(page.locator('#luminosity-calculation-note')).toHaveText('Radius unavailable; surface area and surface flux cannot be derived. Catalog luminosity is shown.')
  await expect(page.locator('#luminosity-calculation-note')).toBeVisible()
  await expect(page.locator('#luminosity-area')).toHaveText('—')
  await expect(page.locator('#luminosity-surface-flux')).toHaveText('—')
  await select(page, 'EZ Aquarii B')
  await expect(page.locator('#luminosity-toggle')).toBeDisabled()
  await expect(page.locator('#luminosity')).toHaveText('—')
  await expect(page.locator('#luminosity-card')).toBeHidden()
  await page.locator('#set-origin').click()
  await select(page, 'Luhman 16 A')
  await page.locator('#luminosity-toggle').click()
  await expect(page.locator('#luminosity-flux-origin-name')).toHaveText('EZ Aquarii B')
  await expect(page.locator('#luminosity-flux-origin-distance')).toHaveText('—')
  await expect(page.locator('#luminosity-flux-origin-value')).toBeHidden()
  await expect(page.locator('#luminosity-flux-bar [data-object-id="ez-aquarii-b"]')).toHaveCount(0)
  await expect(page.locator('#luminosity-flux-bar')).toBeVisible()
  await expect(page.locator('#luminosity-flux-bar .luminosity-object-marker')).toHaveCount(2)
  await expect(page.locator('#luminosity-flux-sun-distance')).toHaveText('1 AU')
  await expect(page.locator('#luminosity-flux-note')).toHaveText('EZ Aquarii B: bolometric luminosity unavailable.')
  await expect(page.locator('#luminosity-flux-bar')).toHaveAttribute('aria-label', /receives 1,360 watts per square meter/)
  await expect(page.locator('#luminosity-distance-axis')).toBeVisible()
  const valueFits = await page.locator('#luminosity-solar').evaluate((value) => value.scrollWidth <= value.clientWidth)
  expect(valueFits).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('luminosity-missing-origin.png') })
})
