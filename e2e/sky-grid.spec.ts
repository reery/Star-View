import { expect, test } from '@playwright/test'
import { PNG } from 'pngjs'
import { hideMilkyWay, openViewer, selectCatalog, starPoint } from './support'

test('sky grids reveal beside the grid button and remain mutually exclusive @mobile', async ({ page, isMobile }, testInfo) => {
  await openViewer(page)
  const grid = page.locator('#toggle-grid')
  const equatorial = page.locator('#toggle-equatorial-grid')
  const galactic = page.locator('#toggle-galactic-grid')
  const scene = page.locator('#scene')
  await expect(equatorial).toBeHidden()
  await expect(galactic).toBeHidden()
  await expect(scene).toHaveAttribute('data-sky-grid', 'off')
  if (isMobile) await grid.tap()
  else await grid.hover()
  await expect(equatorial).toBeVisible()
  await expect(galactic).toBeVisible()
  const mainBounds = (await grid.boundingBox())!
  for (const button of [equatorial, galactic]) {
    const bounds = (await button.boundingBox())!
    expect(bounds.x).toBeGreaterThanOrEqual(0)
    expect(bounds.x + bounds.width).toBeLessThanOrEqual(mainBounds.x)
    expect(bounds.y).toBe(mainBounds.y)
  }
  const sunBefore = await starPoint(page, 'sun')
  await equatorial.click()
  await expect(equatorial).toHaveAttribute('aria-pressed', 'true')
  await expect(galactic).toHaveAttribute('aria-pressed', 'false')
  await expect(scene).toHaveAttribute('data-sky-grid', 'equatorial')
  expect(await starPoint(page, 'sun')).toEqual(sunBefore)
  await expect(page.locator('.sky-grid-label:visible').first()).toBeVisible()
  await galactic.click()
  await expect(equatorial).toHaveAttribute('aria-pressed', 'false')
  await expect(galactic).toHaveAttribute('aria-pressed', 'true')
  await expect(scene).toHaveAttribute('data-sky-grid', 'galactic')
  const flatBefore = await grid.getAttribute('aria-pressed')
  await grid.click()
  await expect(grid).toHaveAttribute('aria-pressed', String(flatBefore !== 'true'))
  await expect(scene).toHaveAttribute('data-sky-grid', 'galactic')
  await galactic.click()
  await expect(scene).toHaveAttribute('data-sky-grid', 'off')
  await expect(page.locator('.sky-grid-labels')).toBeHidden()
  await page.locator('#scene canvas').click({ position: { x: 20, y: 300 } })
  await page.mouse.move(5, 5)
  await expect(equatorial).toBeHidden()
  await grid.focus()
  await page.keyboard.press('Tab')
  await expect(equatorial).toBeFocused()
  await page.keyboard.press('Space')
  await expect(scene).toHaveAttribute('data-sky-grid', 'equatorial')
  await page.screenshot({ path: testInfo.outputPath('equatorial-grid.png') })
})

test('sky grids draw in map and rolled observer views without WebGL errors @mobile', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()) })
  await openViewer(page)
  await hideMilkyWay(page)
  await page.locator('#toggle-grid').click()
  const canvas = page.locator('#scene canvas')
  const off = PNG.sync.read(await canvas.screenshot())
  await page.locator('#toggle-grid').focus()
  await page.locator('#toggle-galactic-grid').click()
  const on = PNG.sync.read(await canvas.screenshot())
  let changedPixels = 0
  for (let offset = 0; offset < on.data.length; offset += 4) {
    if (Math.abs(on.data[offset]! - off.data[offset]!) + Math.abs(on.data[offset + 1]! - off.data[offset + 1]!) + Math.abs(on.data[offset + 2]! - off.data[offset + 2]!) > 10) changedPixels++
  }
  expect(changedPixels).toBeGreaterThan(200)
  await selectCatalog(page, 'nearest-100')
  await expect(page.locator('#scene')).toHaveAttribute('data-sky-grid', 'galactic')
  await page.getByRole('button', { name: 'Filter', exact: true }).click()
  await page.locator('#observer-view').click()
  await expect(page.locator('.sky-grid-label:visible').first()).toBeVisible()
  const labels = () => page.locator('.sky-grid-label:visible').evaluateAll((nodes) => nodes.map((node) => ({ text: node.textContent, transform: (node.parentElement as HTMLElement).style.transform })))
  const beforeRoll = await labels()
  await page.locator('#observer-roll-counterclockwise').click()
  await expect(page.locator('#scene')).toHaveAttribute('data-observer-roll-degrees', '15')
  expect(await labels()).not.toEqual(beforeRoll)
  await page.locator('#observer-telescope').click()
  await expect(page.locator('#scene')).toHaveAttribute('data-sky-grid', 'galactic')
  await page.screenshot({ path: testInfo.outputPath('galactic-observer-grid.png') })
  expect(errors).toEqual([])
})

test('saved views restore one sky grid and older saved views default to off', async ({ page }) => {
  await openViewer(page)
  await page.locator('#toggle-grid').hover()
  await page.locator('#toggle-galactic-grid').click()
  await page.getByRole('button', { name: 'Saved views', exact: true }).click()
  await page.getByRole('textbox', { name: 'View name' }).fill('Galactic grid')
  await page.getByRole('button', { name: 'Save current view', exact: true }).click()
  await expect(page.locator('#saved-views-status')).toHaveText('Saved “Galactic grid”')
  await page.reload()
  await expect(page.locator('#scene')).toHaveAttribute('data-ready', 'true')
  await page.locator('#toggle-grid').hover()
  await page.locator('#toggle-equatorial-grid').click()
  await page.getByRole('button', { name: 'Saved views', exact: true }).click()
  await page.getByRole('row', { name: 'Load saved view Galactic grid' }).click()
  await expect(page.locator('#saved-views-status')).toHaveText('Loaded “Galactic grid”')
  await expect(page.locator('#scene')).toHaveAttribute('data-sky-grid', 'galactic')
  await expect(page.locator('#toggle-equatorial-grid')).toHaveAttribute('aria-pressed', 'false')
  await expect(page.locator('#toggle-galactic-grid')).toHaveAttribute('aria-pressed', 'true')
  await page.evaluate(() => {
    const views = JSON.parse(localStorage.getItem('star-view-saved-views')!)
    delete views[0].settings.skyGridMode
    localStorage.setItem('star-view-saved-views', JSON.stringify(views))
  })
  await page.reload()
  await expect(page.locator('#scene')).toHaveAttribute('data-ready', 'true')
  await page.getByRole('button', { name: 'Saved views', exact: true }).click()
  await page.getByRole('row', { name: 'Load saved view Galactic grid' }).click()
  await expect(page.locator('#saved-views-status')).toHaveText('Loaded “Galactic grid”')
  await expect(page.locator('#scene')).toHaveAttribute('data-sky-grid', 'off')
})
