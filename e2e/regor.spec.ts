import { expect, test } from '@playwright/test'
import { openFilter, openSpecs, openViewer } from './support'

test('Regor exposes separate stellar properties and the measured inner orbit', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await openViewer(page)
  await openFilter(page)
  await page.getByRole('switch', { name: 'Always show bright stars', exact: true }).check()
  await expect(page.locator('#scene-status')).toBeHidden()
  await page.getByLabel('Object visibility distance', { exact: true }).fill('24')
  await page.getByRole('button', { name: 'Filter', exact: true }).click()
  await page.getByRole('button', { name: 'Objects', exact: true }).click()
  await page.getByLabel('Search objects').fill('Regor')
  await page.getByRole('button', { name: 'Select Regor Aa', exact: true }).click()
  await page.getByRole('button', { name: 'Objects', exact: true }).click()
  await openSpecs(page)
  await expect(page.locator('#star-components button')).toHaveText(['Aa', 'Ab', 'Ba', 'Bb', 'C'])
  await expect(page.locator('#mass')).toHaveText('8.3 M☉')
  await expect(page.locator('#radius')).toHaveText('3.4 R☉')
  await expect(page.locator('#luminosity')).toHaveText('110,000 L☉')
  await expect(page.locator('#temperature-row dt')).toHaveText('Temperature T*')
  await expect(page.locator('#temperature')).toHaveText('57,100 ± 1,700 K')
  await expect(page.locator('#temperature-toggle')).toBeDisabled()
  await page.locator('#temperature-row').focus()
  await expect(page.locator('#temperature-source-tooltip')).toBeVisible()
  await expect(page.locator('#temperature-source-tooltip')).toContainText('inner-boundary')
  await page.locator('#temperature-row').blur()
  await page.locator('#selected-object-card').screenshot({ path: testInfo.outputPath('regor-wr-specs.png') })

  await page.getByRole('button', { name: 'Show Regor Ab', exact: true }).click()
  await expect(page.locator('#mass')).toHaveText('26.4 M☉')
  await expect(page.locator('#radius')).toHaveText('13.5 R☉')
  await expect(page.locator('#luminosity')).toHaveText('250,000 L☉')
  await expect(page.locator('#temperature-row dt')).toHaveText('Temperature')
  await expect(page.locator('#temperature')).toHaveText('35,000 K')
  await expect(page.locator('#temperature-toggle')).toBeEnabled()
  await page.locator('#object-system-toggle').click()
  const system = page.locator('#object-system')
  await expect(system).toContainText('5 stars system')
  await expect(system.locator('[data-orbit-spec="period"] dd')).toHaveText('78.524 d')
  await expect(system.locator('[data-orbit-spec="axis"] dd')).toHaveText('1.17 AU')
  await expect(system.locator('[data-stellar-orbit]')).toHaveCount(2)
  await expect(system.locator('[data-barycenter]')).toHaveCount(1)
  await expect(system.getByRole('link', { name: 'Schmutz et al. 2026 (preprint), Table 4' })).toHaveAttribute('href', 'https://arxiv.org/html/2606.27265v1')
  const diagram = system.locator('.stellar-orbit-diagram')
  const sky = await diagram.locator('[data-stellar-orbit]').first().getAttribute('d')
  await system.getByRole('button', { name: 'Top view of stellar orbit', exact: true }).click()
  expect(await diagram.locator('[data-stellar-orbit]').first().getAttribute('d')).not.toBe(sky)
  expect(await system.evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true)
  await page.locator('#selected-object-card').screenshot({ path: testInfo.outputPath('regor-inner-orbit.png') })
  await system.getByRole('button', { name: 'Show Ba–Bb orbit', exact: true }).click()
  await expect(system.locator('[data-stellar-orbit]')).toHaveCount(0)
  await expect(system.locator('[data-orbit-spec="period"] dd')).toHaveText('1.4826 d')
  await expect(system).toContainText('A complete relative orbit is not available for this pair.')
  expect(errors).toEqual([])
})
