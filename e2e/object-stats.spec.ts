import { expect, test } from '@playwright/test'
import { openSpecs } from './support'

test('expands sub-type descriptions and handles one or no classifications @mobile', async ({ page }, testInfo) => {
  await page.goto('/')
  await expect(page.locator('#scene')).toHaveAttribute('data-ready', 'true')
  await openSpecs(page)
  const details = page.locator('#object-subtypes-row')
  const summary = details.locator('summary')
  const list = page.locator('#object-subtypes')
  await expect(page.locator('#object-subtypes-count')).toHaveText('3')
  await expect(summary).toHaveCSS('font-weight', '400')
  await expect(list).toBeHidden()
  await summary.click()
  await expect(list.locator('strong')).toHaveText(['Spectroscopic binary', 'Variable star', 'Main-sequence'])
  await expect(list.locator('p')).toHaveCount(3)
  await expect(list.locator('p').last()).toContainText('hydrogen fusion')
  await expect(list.locator('strong').first()).toHaveCSS('font-weight', '600')
  const layout = await list.evaluate((element) => {
    const lastDescription = element.querySelector('li:last-child p')!.getBoundingClientRect()
    const constellation = document.getElementById('constellation-row')!.getBoundingClientRect()
    return {
      gap: constellation.top - lastDescription.bottom,
      fits: element.scrollWidth <= element.clientWidth,
    }
  })
  expect(layout.gap).toBeGreaterThanOrEqual(8)
  expect(layout.fits).toBe(true)
  await page.locator('#selected-object-card').screenshot({ path: testInfo.outputPath('subtypes-expanded.png') })
  await summary.focus()
  await page.keyboard.press('Enter')
  await expect(list).toBeHidden()
  await page.locator('#selected-object-card').screenshot({ path: testInfo.outputPath('subtypes-collapsed.png') })
  await summary.click()

  const select = async (name: string) => {
    await page.getByRole('button', { name: 'Objects', exact: true }).click()
    await page.getByLabel('Search objects').fill(name)
    await page.getByRole('button', { name: `Select ${name}`, exact: true }).click()
    await page.getByRole('button', { name: 'Objects', exact: true }).click()
    await openSpecs(page)
  }
  await page.getByRole('button', { name: 'Show Sirius B', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Show Sirius B', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(details).toBeHidden()
  await expect(details).not.toHaveAttribute('open')
  await expect(page.locator('#object-subtypes-empty-row')).toBeVisible()
  await expect(page.locator('#object-subtypes-empty-row dd')).toHaveText('—')
  await select('Sun')
  await expect(details).toBeVisible()
  await expect(page.locator('#object-subtypes-empty-row')).toBeHidden()
  await expect(page.locator('#object-subtypes-count')).toHaveText('1')
  await expect(list).toBeHidden()
  await summary.focus()
  await page.keyboard.press('Space')
  await expect(list.locator('strong')).toHaveText('Main-sequence')
  await expect(list.locator('p')).toBeVisible()
})

test('shows selected-object stats and hides empty Sun metadata @mobile', async ({ page }, testInfo) => {
  await page.goto('/')
  await expect(page.locator('#scene')).toHaveAttribute('data-ready', 'true')
  await page.getByRole('button', { name: 'Objects', exact: true }).click()
  await page.getByRole('button', { name: 'Select Sun', exact: true }).click()
  await page.getByRole('button', { name: 'Objects', exact: true }).click()
  await page.getByRole('button', { name: 'Specs', exact: true }).click()
  await expect(page.locator('#constellation-row')).toBeHidden()
  await expect(page.locator('#designations-row')).toBeHidden()
  await expect(page.locator('#designations-empty-row')).toBeVisible()
  await expect(page.locator('#designations-empty')).toHaveText('—')
  await expect(page.locator('#known-planets')).toHaveText('8')
  await expect(page.locator('#object-subtypes-count')).toHaveText('1')
  await expect(page.locator('#object-subtypes')).toBeHidden()
  await page.locator('#object-subtypes-row > summary').click()
  await expect(page.locator('#object-subtypes strong')).toHaveText('Main-sequence')
  await expect(page.locator('#object-subtypes p')).toContainText('hydrogen fusion')
  await expect(page.locator('#apparent-mag')).toHaveText('-26.74')
  expect(await page.locator('#absolute-mag').evaluate((value) => value.parentElement!.nextElementSibling!.querySelector('dt')!.textContent)).toBe('Apparent mag. (V)')
  await page.screenshot({ path: testInfo.outputPath('sun-object-stats.png') })
  await page.getByRole('button', { name: 'Objects', exact: true }).click()
  await page.getByRole('button', { name: 'Select Proxima Centauri', exact: true }).click()
  await page.getByRole('button', { name: 'Objects', exact: true }).click()
  if (await page.locator('#object-specs-toggle').getAttribute('aria-expanded') === 'false') {
    await page.getByRole('button', { name: 'Specs', exact: true }).click()
  }
  await expect(page.locator('#constellation-row')).toBeVisible()
  await expect(page.locator('#designations-row')).toBeVisible()
  await expect(page.locator('#designations-row > summary')).toHaveCSS('font-weight', '400')
  await expect(page.locator('#designations-empty-row')).toBeHidden()
  await expect(page.locator('#known-planets')).toHaveText('2')
  await expect(page.locator('#object-subtypes')).toContainText('variable')
  await expect(page.locator('#apparent-mag')).toHaveText('11.103')
  const subtypeFits = await page.locator('#object-subtypes-row').evaluate((row) => row.scrollWidth <= row.clientWidth)
  expect(subtypeFits).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('proxima-object-stats.png') })
})
