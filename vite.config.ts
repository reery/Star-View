import { existsSync, readFileSync, realpathSync } from 'node:fs'
import { extname, resolve, sep } from 'node:path'
import { defineConfig, type Plugin } from 'vite'
import { writeBrotliSidecars } from './scripts/brotli.ts'
import { CATALOG_DETAIL_ASSET_PATH, catalogDetailAsset, catalogDetailAssets } from './scripts/catalog-detail-assets.ts'

const COMPRESSIBLE = new Set(['.css', '.html', '.js', '.json', '.svg', '.txt', '.xml'])
const CONTENT_TYPES: Record<string, string> = {
  '.css': 'text/css; charset=utf-8',
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.txt': 'text/plain; charset=utf-8',
  '.xml': 'application/xml; charset=utf-8',
}

const CONTENT_SECURITY_POLICY = [
  "default-src 'self'",
  "script-src 'self'",
  "style-src 'self'",
  "img-src 'self' data:",
  "connect-src 'self'",
  "object-src 'none'",
  "base-uri 'none'",
  "form-action 'none'",
  "require-trusted-types-for 'script'",
  "trusted-types 'none'",
].join('; ')

// Meta policies ignore frame-ancestors, so only response headers carry it.
const SECURITY_HEADERS: Record<string, string> = {
  'Content-Security-Policy': `${CONTENT_SECURITY_POLICY}; frame-ancestors 'none'`,
  'X-Frame-Options': 'DENY',
  'X-Content-Type-Options': 'nosniff',
  'Referrer-Policy': 'no-referrer',
  'Cross-Origin-Opener-Policy': 'same-origin',
  'Cross-Origin-Resource-Policy': 'same-origin',
  'Permissions-Policy': 'camera=(), microphone=(), geolocation=(), payment=(), usb=()',
}
const HTTPS_ONLY_HEADERS: Record<string, string> = {
  'Strict-Transport-Security': 'max-age=31536000; includeSubDomains',
}
const IMMUTABLE_CACHE_CONTROL = 'public, max-age=31536000, immutable'

function headerRule(pattern: string, headers: Record<string, string>): string {
  return [pattern, ...Object.entries(headers).map(([name, value]) => `  ${name}: ${value}`)].join('\n')
}

// Dev keeps Vite's inline HMR tooling; production pages get a same-origin-only policy.
function contentSecurityPolicy(): Plugin {
  return {
    name: 'star-view-content-security-policy',
    apply: 'build',
    transformIndexHtml: () => [{
      tag: 'meta',
      attrs: { 'http-equiv': 'Content-Security-Policy', content: CONTENT_SECURITY_POLICY },
      injectTo: 'head-prepend',
    }],
  }
}

// Source-note payloads are already named by content hash, so the browser derives each URL
// from the catalog record instead of downloading a lookup table of bundler-hashed URLs.
function catalogDetailFiles(): Plugin {
  let directory = ''
  return {
    name: 'star-view-catalog-details',
    configResolved(config) {
      directory = resolve(config.root, 'src/data/generated/catalog-details')
    },
    generateBundle() {
      for (const [hash, source] of catalogDetailAssets(directory)) {
        this.emitFile({ type: 'asset', fileName: `assets/catalog-details/${hash}.json`, source })
      }
    },
    configureServer(server) {
      server.middlewares.use((request, response, next) => {
        const hash = CATALOG_DETAIL_ASSET_PATH.exec(request.url?.split('?')[0] ?? '')?.[1]
        if (!hash) return next()
        const content = catalogDetailAsset(directory, hash)
        if (content === undefined) {
          response.statusCode = 404
          response.end('Not found')
          return
        }
        response.setHeader('Content-Type', 'application/json; charset=utf-8')
        response.setHeader('Cache-Control', 'no-cache')
        response.end(content)
      })
    },
  }
}

// Cloudflare static assets read these files from the output directory; neither is served.
function cloudflareAssetConfig(): Plugin {
  return {
    name: 'star-view-cloudflare-assets',
    apply: 'build',
    generateBundle() {
      this.emitFile({
        type: 'asset',
        fileName: '_headers',
        source: [
          '# Generated by vite.config.ts.',
          headerRule('/*', { ...SECURITY_HEADERS, ...HTTPS_ONLY_HEADERS }),
          // The entry document must revalidate before it references a deployment's chunks.
          headerRule('/', { 'Cache-Control': 'no-cache' }),
          headerRule('/index.html', { 'Cache-Control': 'no-cache' }),
          headerRule('/assets/*', { 'Cache-Control': IMMUTABLE_CACHE_CONTROL }),
          headerRule('https://:worker.:account.workers.dev/*', { 'X-Robots-Tag': 'noindex' }),
        ].join('\n\n') + '\n',
      })
      // Cloudflare compresses at the edge; the Brotli sidecars are for `vite preview` only.
      this.emitFile({ type: 'asset', fileName: '.assetsignore', source: '*.br\n' })
    },
  }
}

function acceptsBrotli(header: string | undefined): boolean {
  if (!header) return false
  const encodings = header.split(',').map((part) => {
    const [name, ...parameters] = part.trim().split(';')
    const quality = parameters.find((parameter) => parameter.trim().startsWith('q='))?.split('=')[1]
    return { name: name?.trim().toLowerCase(), quality: quality === undefined ? 1 : Number(quality) }
  })
  const explicit = encodings.find((encoding) => encoding.name === 'br')
  if (explicit) return Number.isFinite(explicit.quality) && explicit.quality > 0
  const wildcard = encodings.find((encoding) => encoding.name === '*')
  return Boolean(wildcard && Number.isFinite(wildcard.quality) && wildcard.quality > 0)
}

function brotliAssets(): Plugin {
  let buildRoot = ''
  let cacheRoot = ''
  return {
    name: 'star-view-brotli-assets',
    enforce: 'post',
    configResolved(config) {
      buildRoot = resolve(config.root, config.build.outDir)
      cacheRoot = resolve(config.cacheDir, 'star-view-brotli')
    },
    async writeBundle(_, bundle) {
      const files = Object.values(bundle)
        .filter((output) => COMPRESSIBLE.has(extname(output.fileName)))
        .map((output) => resolve(buildRoot, output.fileName))
      const { reused, compressed } = await writeBrotliSidecars(files, cacheRoot)
      this.info(`Brotli: ${reused} cached, ${compressed} compressed`)
    },
    configurePreviewServer(server) {
      const outputRoot = realpathSync(resolve(server.config.root, server.config.build.outDir))
      server.middlewares.use((request, response, next) => {
        if (!request.url) return next()
        for (const [name, value] of Object.entries(SECURITY_HEADERS)) response.setHeader(name, value)
        let pathname: string
        try {
          pathname = decodeURIComponent(new URL(request.url, 'http://localhost').pathname)
        } catch {
          response.statusCode = 400
          response.end('Bad request')
          return
        }
        if (pathname === '/' || pathname.endsWith('/index.html')) {
          response.setHeader('Cache-Control', 'no-cache')
        } else if (/\/assets\/.+-[A-Za-z0-9_-]{8,}\./.test(pathname)) {
          response.setHeader('Cache-Control', IMMUTABLE_CACHE_CONTROL)
        }
        const requested = resolve(outputRoot, `.${pathname}`)
        if (requested !== outputRoot && !requested.startsWith(`${outputRoot}${sep}`)) {
          response.statusCode = 403
          response.end('Forbidden')
          return
        }
        // Match Workers' not_found_handling: none for missing deployment assets.
        if (pathname.startsWith('/assets/') && !existsSync(requested)) {
          response.statusCode = 404
          response.setHeader('Cache-Control', 'no-store')
          response.setHeader('Content-Type', 'text/plain; charset=utf-8')
          response.end('Not found')
          return
        }
        const sidecar = `${requested}.br`
        if (!existsSync(sidecar)) return next()
        const resolvedSidecar = realpathSync(sidecar)
        if (!resolvedSidecar.startsWith(`${outputRoot}${sep}`)) {
          response.statusCode = 403
          response.end('Forbidden')
          return
        }
        response.setHeader('Vary', 'Accept-Encoding')
        if (!acceptsBrotli(request.headers['accept-encoding'])) return next()
        response.setHeader('Content-Type', CONTENT_TYPES[extname(requested)] ?? 'application/octet-stream')
        response.setHeader('Content-Encoding', 'br')
        response.end(readFileSync(resolvedSidecar))
      })
    },
  }
}

export default defineConfig(({ mode }) => ({
  plugins: [contentSecurityPolicy(), catalogDetailFiles(), cloudflareAssetConfig(), brotliAssets()],
  // Keep a manual-refresh option for long inspection sessions in Safari.
  server: {
    ...(mode === 'manual' ? { hmr: false } : {}),
    watch: {
      ignored: [/[/\\]src[/\\]data[/\\]generated[/\\].* \d+\.json$/],
    },
  },
}))
