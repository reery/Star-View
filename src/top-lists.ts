/** Catalog record that represents a listed star, and the planet of that host a planet entry opens; generated by scripts/author-top-lists.py. */
export interface TopListObject { catalog: string; id: string; designation: string | null; planet?: string }
/** Ranked lists carry a metric value; descriptive lists carry text fields labelled by the list's columns. Computed lists may carry both. */
interface TopListEntry { name: string; value?: number; fields?: string[]; distance_pc: number; distance_source?: string; note?: string; constellation: string; object: TopListObject | null }
/** How a table shows its values: `unit: 'distance'` values are parsecs shown in the chosen distance unit. */
interface TableSpec { metric?: string; unit?: string; digits?: number; columns?: string[] }
interface TopListGroup extends TableSpec { kind?: string; title: string; entries: TopListEntry[] }
/** `groups` lists show one small table per group, side by side. */
interface TopList extends TableSpec {
  id: string; title: string; markers?: string
  method?: string; source?: { label: string; url: string }; entries?: TopListEntry[]; groups?: TopListGroup[]
}

interface TopListOptions {
  distanceUnit: DistanceUnit
  onSelect(object: TopListObject): void
}

/** Each kind's mark, sized by luminosity class: a vivid spectrum colour, placed so neighbouring kinds stay distinct (red, orange, yellow dwarfs),
 * or the map colour of a compact object type. Planet hosts add an orbit. */
type KindMark = { type?: Star['type']; spectral?: string; kelvin?: number; size: number; orbit?: true }
const kindMarks: Record<string, KindMark> = {
  'red-dwarfs': { kelvin: 1900, size: 7 }, 'orange-dwarfs': { kelvin: 3600, size: 7 }, 'yellow-dwarfs': { kelvin: 5700, size: 7 },
  'f-dwarfs': { kelvin: 6800, size: 8 }, 'a-dwarfs': { kelvin: 9000, size: 8 }, 'b-dwarfs': { kelvin: 16000, size: 9 }, 'o-stars': { kelvin: 35000, size: 10 },
  subgiants: { kelvin: 5000, size: 9 }, giants: { kelvin: 3800, size: 11 }, 'bright-giants': { kelvin: 4800, size: 12 }, supergiants: { kelvin: 2600, size: 14 },
  'wolf-rayet': { kelvin: 50000, size: 10 }, 'carbon-stars': { kelvin: 1850, size: 11 }, cepheids: { kelvin: 6000, size: 12 }, miras: { kelvin: 2300, size: 12 },
  'white-dwarfs': { type: 'white_dwarf', kelvin: 10000, size: 5 }, 'brown-dwarfs': { type: 'brown_dwarf', spectral: 'T5', size: 6 },
  'planet-hosts': { kelvin: 5700, size: 6, orbit: true }, 'neutron-stars': { type: 'neutron_star', size: 5 }, pulsars: { type: 'pulsar', size: 5 },
  'black-holes': { type: 'black_hole', size: 7 },
}

function kindMark(kind: string): HTMLElement {
  const { type, spectral = null, kelvin, size, orbit } = kindMarks[kind]!
  const mark = document.createElement('i')
  mark.className = `star-swatch top-list-kind-mark${orbit ? ' is-orbited' : ''}`
  mark.setAttribute('aria-hidden', 'true')
  mark.style.setProperty('--kind-size', `${size}px`)
  const color = type ? starDisplayColor({ type, temperature_k: kelvin ?? null, spectral_type: spectral }, 'exaggerated') : temperatureSpectrumColor(kelvin!)
  mark.style.background = color.getStyle()
  return mark
}

const lists = data.lists as TopList[]
// Collapsed sidebar icons; lists added later fall back to the Top lists trophy.
const listIcons: Record<string, IconNode> = {
  largest: Maximize, hottest: Flame, supernova: Sparkles, 'solar-type': Sun, 'solar-analogs': EqualApproximately, 'solar-twins': Equal, 'pioneer-plaque': Radio,
  'nearest-kinds': LayoutGrid, encounters: Merge, 'proper-motion': MoveUpRight, metallicity: Atom, planets: Orbit, 'fastest-pulsars': Gauge,
}
const solarRadiiPerAu = AU_METERS / SOLAR_RADIUS_METERS
const solarOrbits = planetarySystems.systems.find(({ hostStarId }) => hostStarId === 'sun')!.planets
  .map((planet) => ({ name: planet.name, radius: planet.semiMajorAxisAu * solarRadiiPerAu }))

/** Orbits inside the listed range, plus the nearest orbit beyond each end. */
function orbitMarkers(entries: readonly TopListEntry[]) {
  const max = entries[0]!.value!, min = entries.at(-1)!.value!
  const above = solarOrbits.find((orbit) => orbit.radius > max)
  const below = solarOrbits.findLast((orbit) => orbit.radius < min)
  return solarOrbits.filter((orbit) => orbit === above || orbit === below || (orbit.radius >= min && orbit.radius <= max))
}

function cell(content: string | Node, className?: string): HTMLTableCellElement {
  const td = document.createElement('td')
  if (className) td.className = className
  td.append(content)
  return td
}

function tableParts() {
  const table = document.createElement('table')
  table.className = 'top-list'
  const cols = table.appendChild(document.createElement('colgroup'))
  return { table, cols, head: table.createTHead().insertRow(), body: table.createTBody() }
}

export function initializeTopLists(signal: AbortSignal, options: () => TopListOptions) {
  const terms = document.getElementById('top-lists-terms')!
  const heading = document.getElementById('top-lists-title')!
  const cols = document.getElementById('top-lists-cols')!
  const head = document.getElementById('top-lists-head')!
  const body = document.getElementById('top-lists-rows')!
  const groups = document.getElementById('top-lists-groups')!
  const source = document.getElementById('top-lists-source') as HTMLAnchorElement
  const attribution = document.getElementById('top-lists-attribution')!
  const method = document.getElementById('top-lists-method')!
  const missing = document.getElementById('top-lists-missing')!
  const notes = document.getElementById('top-lists-notes')!
  const scroll = document.getElementById('top-lists-detail')!.querySelector<HTMLElement>('.card-scroll-content')!
  let selected = lists[0]!

  terms.replaceChildren(...lists.map((list) => {
    const button = document.createElement('button')
    button.type = 'button'
    button.className = 'glossary-term'
    button.append(
      Object.assign(document.createElement('span'), { className: 'glossary-term-icon', title: list.title }),
      Object.assign(document.createElement('span'), { className: 'glossary-term-label', textContent: list.title }),
    )
    button.firstElementChild!.append(createElement(listIcons[list.id] ?? Trophy, { 'stroke-width': 1.7, 'aria-hidden': 'true' }))
    button.dataset.list = list.id
    button.setAttribute('aria-controls', 'top-lists-detail')
    return button
  }))

  /** Fills one table; `group` tags rows of a grouped list so a click finds its entry. */
  const fillTable = (parts: { cols: HTMLElement; head: HTMLElement; body: HTMLElement }, spec: TableSpec, entries: readonly TopListEntry[], group?: number) => {
    const { distanceUnit } = options()
    const distanceScale = distanceUnit === 'ly' ? LIGHT_YEARS_PER_PARSEC : 1
    // Literature distances carry about three significant figures.
    const distanceText = (pc: number) => (pc * distanceScale).toLocaleString('en-US', { maximumSignificantDigits: 3 })
    const { metric, columns } = spec
    const unit = spec.unit === 'distance' ? distanceUnit : spec.unit
    parts.cols.parentElement!.classList.toggle('top-list-fields', !!columns && !metric)
    parts.cols.parentElement!.dataset.list = selected.id
    const valueCols = [...metric ? ['top-list-number'] : [], ...columns?.map((_, i) => `top-list-field-${i}`) ?? []]
    parts.cols.replaceChildren(...['top-list-rank', '', 'top-list-number', ...valueCols, 'top-list-constellation'].map((className) => {
      const col = document.createElement('col')
      if (className) col.className = className
      return col
    }))
    parts.head.replaceChildren(...['#', 'Name', `Distance (${distanceUnit})`, ...metric ? [unit ? `${metric} (${unit})` : metric] : [], ...columns ?? [], 'Constellation'].map((label) => {
      const th = document.createElement('th')
      th.scope = 'col'
      th.textContent = label
      return th
    }))
    const markers = selected.markers === 'solar-orbits' ? orbitMarkers(entries) : []
    const marker = (orbit: typeof markers[number]) => {
      const row = document.createElement('tr')
      row.className = 'top-list-marker'
      const td = cell(`Orbit of ${orbit.name} · ${formatNumber(orbit.radius, 0)} ${unit}`)
      td.colSpan = parts.head.childElementCount
      row.append(td)
      return row
    }
    const rows: HTMLTableRowElement[] = []
    entries.forEach((entry, index) => {
      // Markers descend with the ranked values, so each lands above the first smaller star.
      while (markers.length && markers.at(-1)!.radius > entry.value!) rows.push(marker(markers.pop()!))
      const row = document.createElement('tr')
      let name: string | Node = entry.name
      if (entry.object) {
        row.dataset.entry = String(index)
        if (group !== undefined) row.dataset.group = String(group)
        const button = document.createElement('button')
        button.type = 'button'
        button.className = 'top-list-select'
        button.textContent = entry.name
        button.setAttribute('aria-label', `Select ${entry.name}`)
        name = button
      } else {
        row.className = 'is-missing'
        row.title = 'Not in Star View’s catalogs'
      }
      const distance = cell(distanceText(entry.distance_pc))
      if (entry.distance_source) distance.title = entry.distance_source
      // Fixed decimals keep a ranked column aligned (6.90 below 10.39).
      const valueText = (value: number) => spec.unit === 'distance' ? distanceText(value)
        : value.toLocaleString('en-US', { minimumFractionDigits: spec.digits ?? 0, maximumFractionDigits: spec.digits ?? 0 })
      const value = entry.value === undefined ? [] : [cell(valueText(entry.value))]
      // Fields can exceed their column, so each carries its full text as a tooltip.
      const values = [...value, ...entry.fields?.map((field) => {
        const td = cell(field || '—')
        if (field) td.title = field
        return td
      }) ?? []]
      // Notes add context to the last value, such as a differing reviewed value or an expected supernova time.
      if (entry.note) values.at(-1)!.append(' *')
      row.append(cell(String(index + 1)), cell(name), distance, ...values, cell(entry.constellation))
      rows.push(row)
    })
    rows.push(...markers.reverse().map(marker))
    parts.body.replaceChildren(...rows)
  }

  const render = () => {
    for (const button of terms.querySelectorAll<HTMLButtonElement>('button')) {
      button.setAttribute('aria-current', String(button.dataset.list === selected.id))
    }
    heading.textContent = selected.title
    cols.parentElement!.hidden = !!selected.groups
    groups.hidden = !selected.groups
    // Tables with a value column need the full card width and wrap below each other.
    groups.classList.toggle('has-metrics', !!selected.groups?.some((group) => group.metric))
    if (selected.groups) {
      groups.replaceChildren(...selected.groups.map((group, index) => {
        const section = document.createElement('section')
        section.className = 'top-list-group'
        const parts = tableParts()
        fillTable(parts, group, group.entries, index)
        const title = Object.assign(document.createElement('h4'), { className: 'card-subgroup-heading top-list-group-heading' })
        title.append(...group.kind ? [kindMark(group.kind)] : [], group.title)
        section.append(title, parts.table)
        return section
      }))
    } else {
      fillTable({ cols, head, body }, selected, selected.entries!)
    }
    const entries = selected.groups?.flatMap((group) => group.entries) ?? selected.entries!
    const noted = entries.filter((entry) => entry.note)
    notes.hidden = !noted.length
    notes.textContent = noted.map((entry) => `* ${entry.name}: ${entry.note}`).join('\n')
    method.textContent = selected.method ? `${selected.method} ` : ''
    missing.hidden = entries.every((entry) => entry.object)
    attribution.hidden = !selected.source
    if (selected.source) {
      source.href = selected.source.url
      source.textContent = selected.source.label
    }
  }

  terms.addEventListener('click', (event) => {
    const id = event.target instanceof Element ? event.target.closest<HTMLButtonElement>('button')?.dataset.list : undefined
    const list = lists.find((candidate) => candidate.id === id)
    if (!list || list === selected) return
    selected = list
    render()
    scroll.scrollTop = 0
  }, { signal })
  scroll.addEventListener('click', (event) => {
    const row = event.target instanceof Element ? event.target.closest<HTMLElement>('tr[data-entry]') : null
    if (!row) return
    const entries = row.dataset.group === undefined ? selected.entries! : selected.groups![Number(row.dataset.group)]!.entries
    const object = entries[Number(row.dataset.entry)]!.object
    if (object) options().onSelect(object)
  }, { signal })
  return { open: render }
}
